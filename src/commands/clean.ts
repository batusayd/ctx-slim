import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { CleanOptions } from '../types';
import {
  CTX_SLIM_END_MARKER,
  CTX_SLIM_START_MARKER,
  getClaudeSettingsDenyRules,
} from '../utils/templates';
import { c, log, printBanner } from '../utils/ui';

const IGNORE_HEADER_MARKER = '# Generated by ctx-slim — AI Context & Token Optimizer';

function removeDirIfEmpty(dirPath: string): void {
  if (!fs.existsSync(dirPath)) return;
  try {
    const entries = fs.readdirSync(dirPath);
    if (entries.length === 0) {
      fs.rmdirSync(dirPath);
    }
  } catch {
    // Ignore errors
  }
}

/**
 * Strips the `<!-- ctx-slim:start --> ... <!-- ctx-slim:end -->` block from a markdown file.
 * If user content remains outside the block, keeps the file with user content intact.
 * If no content remains, deletes the file.
 */
function cleanMarkedMarkdownFile(filePath: string): 'deleted' | 'stripped' | 'none' {
  if (!fs.existsSync(filePath)) return 'none';

  try {
    const content = fs.readFileSync(filePath, 'utf8');
    const startIdx = content.indexOf(CTX_SLIM_START_MARKER);
    const endIdx = content.indexOf(CTX_SLIM_END_MARKER);

    if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
      return 'none';
    }

    const before = content.slice(0, startIdx).trimEnd();
    const after = content.slice(endIdx + CTX_SLIM_END_MARKER.length).trimStart();
    const remaining = [before, after].filter(Boolean).join('\n\n').trim();

    if (remaining.length === 0) {
      fs.unlinkSync(filePath);
      return 'deleted';
    } else {
      fs.writeFileSync(filePath, remaining + '\n', 'utf8');
      return 'stripped';
    }
  } catch {
    return 'none';
  }
}

/**
 * Removes ctx-slim's `permissions.deny` entries from `.claude/settings.json` while preserving user settings.
 */
function cleanClaudeSettingsJson(settingsPath: string): 'deleted' | 'cleaned' | 'none' {
  if (!fs.existsSync(settingsPath)) return 'none';

  try {
    const raw = fs.readFileSync(settingsPath, 'utf8');
    const parsed = JSON.parse(raw);
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return 'none';

    const allKnownRules = new Set<string>(
      getClaudeSettingsDenyRules([
        { id: 'node-ts', name: 'Node', matchedFiles: [] },
        { id: 'python', name: 'Python', matchedFiles: [] },
        { id: 'rust', name: 'Rust', matchedFiles: [] },
        { id: 'php', name: 'PHP', matchedFiles: [] },
      ])
    );

    const obj = parsed as Record<string, unknown>;
    const perms = obj.permissions as Record<string, unknown> | undefined;
    if (!perms || typeof perms !== 'object' || !Array.isArray(perms.deny)) {
      return 'none';
    }

    const beforeLen = perms.deny.length;
    const filteredDeny = perms.deny.filter(
      (r: unknown) => typeof r !== 'string' || !allKnownRules.has(r)
    );
    perms.deny = filteredDeny;

    if (filteredDeny.length === beforeLen) {
      return 'none';
    }

    if (filteredDeny.length === 0) {
      delete perms.deny;
    }
    if (Object.keys(perms).length === 0) {
      delete obj.permissions;
    }

    if (Object.keys(obj).length === 0) {
      fs.unlinkSync(settingsPath);
      return 'deleted';
    } else {
      fs.writeFileSync(settingsPath, JSON.stringify(obj, null, 2) + '\n', 'utf8');
      return 'cleaned';
    }
  } catch {
    return 'none';
  }
}

export function runCleanCommand(options: CleanOptions): void {
  const cwd = options.global ? os.homedir() : path.resolve(options.cwd);

  if (!options.quiet) {
    printBanner();
    log.step(
      options.global
        ? 'Removing GLOBAL ctx-slim rules and commands from'
        : 'Removing ctx-slim generated files and hooks from',
      cwd
    );
    console.log('');
  }

  let removedCount = 0;

  // 1. Clean marked markdown files non-destructively
  const markedTargets = options.global
    ? ['.claude/CLAUDE.md', '.antigravity/rules.md']
    : ['CLAUDE.md', '.antigravity/rules.md'];

  for (const relPath of markedTargets) {
    const fullPath = path.join(cwd, relPath);
    const res = cleanMarkedMarkdownFile(fullPath);
    if (res === 'deleted') {
      removedCount++;
      if (!options.quiet) {
        log.success(`Removed ${c.bold(c.brightCyan(relPath))}`);
      }
    } else if (res === 'stripped') {
      removedCount++;
      if (!options.quiet) {
        log.success(
          `Removed ctx-slim block from ${c.bold(c.brightCyan(relPath))} ${c.gray('(user rules preserved intact)')}`
        );
      }
    }
  }

  // 2. Clean .claude/settings.json non-destructively
  const settingsRel = '.claude/settings.json';
  const settingsRes = cleanClaudeSettingsJson(path.join(cwd, settingsRel));
  if (settingsRes === 'deleted') {
    removedCount++;
    if (!options.quiet) {
      log.success(`Removed ${c.bold(c.brightCyan(settingsRel))}`);
    }
  } else if (settingsRes === 'cleaned') {
    removedCount++;
    if (!options.quiet) {
      log.success(
        `Cleaned ctx-slim deny rules from ${c.bold(c.brightCyan(settingsRel))} ${c.gray('(user settings preserved)')}`
      );
    }
  }

  // 3. Remove slash commands and project ignore/map files
  const directDeleteTargets = options.global
    ? [
        '.claude/commands/diff.md',
        '.claude/commands/plan-lite.md',
        '.claude/commands/handoff.md',
        '.claude/commands/slim.md',
      ]
    : [
        '.claudeignore',
        '.antigravityignore',
        '.aiignore',
        '.claude/commands/diff.md',
        '.claude/commands/plan-lite.md',
        '.claude/commands/handoff.md',
        '.claude/commands/slim.md',
        'REPO_MAP.md',
        'CONTEXT_STATE.md',
      ];

  for (const relPath of directDeleteTargets) {
    const fullPath = path.join(cwd, relPath);
    if (!fs.existsSync(fullPath)) continue;

    // For ignore files, verify they were generated by ctx-slim unless --force is passed
    if (relPath.endsWith('ignore') && !options.force) {
      try {
        const content = fs.readFileSync(fullPath, 'utf8');
        if (!content.includes(IGNORE_HEADER_MARKER)) {
          if (!options.quiet) {
            log.warn(
              `Skipped ${c.bold(relPath)} ${c.gray('(custom ignore file; pass --force to delete)')}`
            );
          }
          continue;
        }
      } catch {
        continue;
      }
    }

    try {
      fs.unlinkSync(fullPath);
      removedCount++;
      if (!options.quiet) {
        log.success(`Removed ${c.bold(c.brightCyan(relPath))}`);
      }
    } catch {
      if (!options.quiet) {
        log.warn(`Could not remove ${relPath}`);
      }
    }
  }

  // Clean up empty directories if we created them
  removeDirIfEmpty(path.join(cwd, '.claude', 'commands'));
  removeDirIfEmpty(path.join(cwd, '.claude'));
  removeDirIfEmpty(path.join(cwd, '.antigravity'));

  // 4. Remove or clean .git/hooks/post-commit (project mode)
  if (!options.global) {
    const hookPath = path.join(cwd, '.git', 'hooks', 'post-commit');
    if (fs.existsSync(hookPath)) {
      try {
        const hookContent = fs.readFileSync(hookPath, 'utf8');
        if (hookContent.includes('# --- Added by ctx-slim ---')) {
          const cleaned = hookContent.split('# --- Added by ctx-slim ---')[0].trimEnd() + '\n';
          fs.writeFileSync(hookPath, cleaned, { encoding: 'utf8', mode: 0o755 });
          removedCount++;
          if (!options.quiet) {
            log.success(
              `Cleaned ctx-slim block from ${c.bold(c.brightCyan('.git/hooks/post-commit'))}`
            );
          }
        } else if (hookContent.includes('ctx-slim post-commit hook')) {
          fs.unlinkSync(hookPath);
          removedCount++;
          if (!options.quiet) {
            log.success(`Removed Git Hook ${c.bold(c.brightCyan('.git/hooks/post-commit'))}`);
          }
        }
      } catch {
        // Ignore hook errors
      }
    }

    const excludePath = path.join(cwd, '.git', 'info', 'exclude');
    if (fs.existsSync(excludePath)) {
      try {
        const excludeContent = fs.readFileSync(excludePath, 'utf8');
        if (excludeContent.includes('# --- ctx-slim local context files ---')) {
          const cleanedExclude =
            excludeContent.split('# --- ctx-slim local context files ---')[0].trimEnd() + '\n';
          fs.writeFileSync(excludePath, cleanedExclude, 'utf8');
        }
      } catch {
        // Ignore exclude errors
      }
    }
  }

  if (!options.quiet) {
    console.log('');
    if (removedCount > 0) {
      console.log(
        `  ${c.bgGreen(c.bold(' CLEANED '))} ${c.bold(`Successfully cleaned ${removedCount} ctx-slim item(s).`)}`
      );
    } else {
      log.info('No ctx-slim files were found.');
    }
    console.log('');
  }
}
