const IGNORE_HEADER_MARKER = '# Generated by ctx-slim — AI Context & Token Optimizer';

/**
 * Safely writes or updates a markdown rule file using `<!-- ctx-slim:start -->` and `<!-- ctx-slim:end -->` markers.
 * Never destroys existing user content (even if the user mentioned the word "ctx-slim" in their own notes).
 */
function upsertMarkedMarkdownFile(
  filePath: string,
  markedBlock: string
): 'created' | 'updated' | 'appended' {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  if (!fs.existsSync(filePath)) {
    fs.writeFileSync(filePath, markedBlock.trimEnd() + '\n', 'utf8');
    return 'created';
  }

  const existing = fs.readFileSync(filePath, 'utf8');
  const startIdx = existing.indexOf(CTX_SLIM_START_MARKER);
  const endIdx = existing.indexOf(CTX_SLIM_END_MARKER);

  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const before = existing.slice(0, startIdx);
    const after = existing.slice(endIdx + CTX_SLIM_END_MARKER.length);
    const updated = before + markedBlock.trim() + after;
    fs.writeFileSync(filePath, updated, 'utf8');
    return 'updated';
  }

  // Existing user file without markers -> preserve 100% of user content and append our bounded block
  const separator = existing.endsWith('\n\n') ? '' : existing.endsWith('\n') ? '\n' : '\n\n';
  const appended = existing + separator + markedBlock.trimEnd() + '\n';
  fs.writeFileSync(filePath, appended, 'utf8');
  return 'appended';
}

function writeIgnoreOrCommandFileSafe(
  filePath: string,
  content: string,
  force: boolean
): 'created' | 'updated' | 'skipped' {
  const exists = fs.existsSync(filePath);
  if (exists && !force) {
    try {
      const existing = fs.readFileSync(filePath, 'utf8');
      const isOurIgnoreFile = existing.startsWith(IGNORE_HEADER_MARKER) || existing.includes(IGNORE_HEADER_MARKER);
      const isOurSlashCmd = filePath.replace(/\\/g, '/').includes('.claude/commands/');
      if (!isOurIgnoreFile && !isOurSlashCmd) {
        return 'skipped';
      }
    } catch {
      return 'skipped';
    }
  }

  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(filePath, content, 'utf8');
  return exists ? 'updated' : 'created';
}

/**
 * Non-destructively merges official Claude Code `permissions.deny` rules into `.claude/settings.json`.
 */
function upsertClaudeSettingsJson(
  settingsPath: string,
  stacks: DetectedStack[]
): 'created' | 'updated' | 'skipped' {
  const dir = path.dirname(settingsPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  const denyRulesToAdd = getClaudeSettingsDenyRules(stacks);
  let existed = false;
  let settingsObj: Record<string, unknown> = {};

  if (fs.existsSync(settingsPath)) {
    existed = true;
    try {
      const raw = fs.readFileSync(settingsPath, 'utf8');
      const parsed = JSON.parse(raw);
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
        settingsObj = parsed as Record<string, unknown>;
      } else {
        return 'skipped';
      }
    } catch {
      // If user has malformed JSON, don't touch it
      return 'skipped';
    }
  }

  if (!settingsObj.permissions || typeof settingsObj.permissions !== 'object' || Array.isArray(settingsObj.permissions)) {
    settingsObj.permissions = {};
  }

  const perms = settingsObj.permissions as Record<string, unknown>;
  const existingDeny = Array.isArray(perms.deny)
    ? perms.deny.filter((x): x is string => typeof x === 'string')
    : [];

  const mergedSet = new Set<string>(existingDeny);
  for (const rule of denyRulesToAdd) {
    mergedSet.add(rule);
  }
  perms.deny = Array.from(mergedSet);

  fs.writeFileSync(settingsPath, JSON.stringify(settingsObj, null, 2) + '\n', 'utf8');
  return existed ? 'updated' : 'created';
}

function resolveVerifiedSelfCliPath(): string | undefined {
  try {
    const candidateIndex = path.resolve(__dirname, '..', 'index.js');
    const candidatePkg = path.resolve(__dirname, '..', '..', 'package.json');
    if (fs.existsSync(candidateIndex) && fs.existsSync(candidatePkg)) {
      const pkg = JSON.parse(fs.readFileSync(candidatePkg, 'utf8'));
      if (pkg && pkg.name === 'ctx-slim') {
        return candidateIndex;
      }
    }
  } catch {
    // Fallback to undefined
  }
  return undefined;
}

export function runInitCommand(options: InitOptions): void {
  if (options.global) {
    runGlobalInit(options);
    return;
  }

  const cwd = path.resolve(options.cwd);
  const projectName = path.basename(cwd);

  if (!options.quiet) {
    printBanner();
    log.step('Initializing ctx-slim in', cwd);
    console.log('');
  }

  // 1. Detect Tech Stack
  const stacks = detectStacks(cwd);
  if (!options.quiet) {
    if (stacks.length > 0) {
      const stackSummary = stacks
        .map((s) => `${c.bold(c.brightCyan(s.name))} ${c.gray(`(${s.matchedFiles.slice(0, 3).join(', ')})`)}`)
        .join(' + ');
      log.success(`Detected Tech Stack: ${stackSummary}`);
    } else {
      log.info(`No specific lockfile detected — applying universal polyglot optimization profile.`);
    }
  }

  // 2. Configure official Claude Code `.claude/settings.json` (`permissions.deny`)
  const claudeSettingsPath = path.join(cwd, '.claude', 'settings.json');
  const settingsStatus = upsertClaudeSettingsJson(claudeSettingsPath, stacks);
  if (!options.quiet) {
    logFileStatus(
      '.claude/settings.json',
      settingsStatus,
      'Official Claude Code permissions.deny rules for lockfiles & build bloat'
    );
  }

  // 3. Generate .antigravityignore, .aiignore, and .claudeignore
  const ignoreContent = generateIgnoreContent(stacks);
  const ignoreTargets = ['.antigravityignore', '.aiignore', '.claudeignore'];

  for (const target of ignoreTargets) {
    const fullPath = path.join(cwd, target);
    const status = writeIgnoreOrCommandFileSafe(fullPath, ignoreContent, options.force);
    if (!options.quiet) {
      logFileStatus(target, status, 'Ignore rules for Antigravity, repo mapper & AI indexers');
    }
  }

  // 4. Non-destructively upsert CLAUDE.md and .antigravity/rules.md using bounded markers
  const claudeMdPath = path.join(cwd, 'CLAUDE.md');
  const claudeStatus = upsertMarkedMarkdownFile(
    claudeMdPath,
    generateClaudeMd(projectName, stacks)
  );
  if (!options.quiet) {
    logFileStatus(
      'CLAUDE.md',
      claudeStatus,
      'Compact (~150 tok) non-destructive protocol block (preserves custom rules)'
    );
  }

  const agRulesPath = path.join(cwd, '.antigravity', 'rules.md');
  const agStatus = upsertMarkedMarkdownFile(
    agRulesPath,
    generateAntigravityRulesMd(projectName, stacks)
  );
  if (!options.quiet) {
    logFileStatus(
      '.antigravity/rules.md',
      agStatus,
      'Antigravity targeted line-range protocol (preserves custom rules)'
    );
  }

  // 5. Generate .claude/commands/*.md for native slash command execution
  const slashCommands = generateClaudeSlashCommands();
  for (const [fileName, cmdContent] of Object.entries(slashCommands)) {
    const cmdPath = path.join(cwd, '.claude', 'commands', fileName);
    writeIgnoreOrCommandFileSafe(cmdPath, cmdContent, options.force);
  }
  if (!options.quiet) {
    log.success(
      `Configured Slash Commands: ${c.brightCyan('/diff')}, ${c.brightCyan('/plan-lite')}, ${c.brightCyan('/handoff')}, ${c.brightCyan('/slim')}`
    );
  }

  // 6. Generate initial REPO_MAP.md
  const mapResult = buildRepoMap({ cwd, output: 'REPO_MAP.md', quiet: true });
  fs.writeFileSync(path.join(cwd, 'REPO_MAP.md'), mapResult.markdown, 'utf8');
  if (!options.quiet) {
    log.success(
      `Generated ${c.bold(c.brightCyan('REPO_MAP.md'))} ${c.gray(`(${formatNumber(mapResult.totalFiles)} files, ${formatNumber(mapResult.totalSymbols)} symbols, ${mapResult.savingsPercent.toFixed(1)}% smaller than raw source)`)}`
    );
  }

  // 7. Optional Git Hook (--with-hooks)
  if (options.withHooks) {
    installGitPostCommitHook(cwd, options.quiet);
  } else if (!options.quiet) {
    const gitDir = path.join(cwd, '.git');
    if (fs.existsSync(gitDir)) {
      log.info(
        `Tip: Run ${c.cyan('ctx-slim init --with-hooks')} or ${c.cyan('ctx-slim watch')} to keep REPO_MAP.md synced automatically.`
      );
    }
  }

  if (!options.quiet) {
    console.log('');
    console.log(`  ${c.bgGreen(c.bold(' READY '))} ${c.bold('Project context optimization configured safely!')}`);
    console.log(
      `  ${c.gray('Next: Run')} ${c.brightCyan('ctx-slim stats')} ${c.gray('to inspect scenario-based token & cost estimates.')}`
    );
    console.log('');
  }
}

function logFileStatus(
  relPath: string,
  status: 'created' | 'updated' | 'appended' | 'skipped',
  desc: string
): void {
  if (status === 'created') {
    log.success(`Created ${c.bold(c.brightCyan(relPath))} ${c.gray('— ' + desc)}`);
  } else if (status === 'updated') {
    log.success(`Updated ${c.bold(c.brightCyan(relPath))} ${c.gray('— ' + desc)}`);
  } else if (status === 'appended') {
    log.success(
      `Appended to ${c.bold(c.brightCyan(relPath))} ${c.gray('— Existing user rules preserved untouched')}`
    );
  } else {
    log.warn(
      `Skipped ${c.bold(relPath)} ${c.gray('(already exists; pass --force to overwrite)')}`
    );
  }
}

function runGlobalInit(options: InitOptions): void {
  const homeDir = os.homedir();

  if (!options.quiet) {
    printBanner();
    log.step('Configuring ctx-slim GLOBALLY (non-destructive) in', homeDir);
    console.log('');
  }

  // 1. Global Claude Code settings.json (`~/.claude/settings.json`)
  const globalSettingsPath = path.join(homeDir, '.claude', 'settings.json');
  const settingsStatus = upsertClaudeSettingsJson(globalSettingsPath, []);
  if (!options.quiet) {
    logFileStatus(
      '~/.claude/settings.json',
      settingsStatus,
      'Global permissions.deny rules for lockfiles & build artifacts'
    );
  }

  // 2. Global Claude Code Rules (`~/.claude/CLAUDE.md`) — Non-destructive marker upsert!
  const globalClaudeMd = path.join(homeDir, '.claude', 'CLAUDE.md');
  const claudeStatus = upsertMarkedMarkdownFile(
    globalClaudeMd,
    generateClaudeMd('Global Profile', [])
  );
  if (!options.quiet) {
    logFileStatus(
      '~/.claude/CLAUDE.md',
      claudeStatus,
      'Compact (~150 tok) global protocol block (existing rules preserved)'
    );
  }

  // 3. Global Claude Code Slash Commands (`~/.claude/commands/*.md`)
  const slashCommands = generateClaudeSlashCommands();
  for (const [fileName, cmdContent] of Object.entries(slashCommands)) {
    const cmdPath = path.join(homeDir, '.claude', 'commands', fileName);
    writeIgnoreOrCommandFileSafe(cmdPath, cmdContent, options.force);
  }
  if (!options.quiet) {
    log.success(
      `Installed Global Slash Commands in ${c.bold(c.brightCyan('~/.claude/commands/'))}: ${c.brightCyan('/diff')}, ${c.brightCyan('/plan-lite')}, ${c.brightCyan('/handoff')}, ${c.brightCyan('/slim')}`
    );
  }

  // 4. Global Antigravity Rules (`~/.antigravity/rules.md`) — Non-destructive marker upsert!
  const globalAgRules = path.join(homeDir, '.antigravity', 'rules.md');
  const agStatus = upsertMarkedMarkdownFile(
    globalAgRules,
    generateAntigravityRulesMd('Global Profile', [])
  );
  if (!options.quiet) {
    logFileStatus(
      '~/.antigravity/rules.md',
      agStatus,
      'Global Antigravity protocol block (existing rules preserved)'
    );
  }

  if (!options.quiet) {
    console.log('');
    console.log(
      `  ${c.bgGreen(c.bold(' GLOBAL READY '))} ${c.bold('ContextSlim is now active across your environment!')}`
    );
    console.log(
      `  ${c.gray('Tip: Run')} ${c.brightCyan('ctx-slim map')} ${c.gray('(or')} ${c.brightCyan('ctx-slim watch')}${c.gray(') in any repo to generate/sync its REPO_MAP.md.')}`
    );
    console.log('');
  }
}

function installGitPostCommitHook(cwd: string, quiet?: boolean): void {
  const gitDir = path.join(cwd, '.git');
  if (!fs.existsSync(gitDir)) {
    if (!quiet) {
      log.warn(`Skipped Git hook installation: ${c.yellow('.git/')} directory not found.`);
    }
    return;
  }

  const hooksDir = path.join(gitDir, 'hooks');
  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }

  const hookPath = path.join(hooksDir, 'post-commit');
  const verifiedCliPath = resolveVerifiedSelfCliPath();
  const hookScript = generatePostCommitHook(verifiedCliPath);

  if (fs.existsSync(hookPath)) {
    const existing = fs.readFileSync(hookPath, 'utf8');
    if (!existing.includes('ctx-slim post-commit hook')) {
      const appended =
        existing.trimEnd() +
        '\n\n# --- Added by ctx-slim ---\n' +
        hookScript.replace(/^#!\/bin\/sh\r?\n/, '');
      fs.writeFileSync(hookPath, appended, { encoding: 'utf8', mode: 0o755 });
    } else if (existing.includes('# --- Added by ctx-slim ---')) {
      const before = existing.split('# --- Added by ctx-slim ---')[0].trimEnd();
      const updated =
        before +
        '\n\n# --- Added by ctx-slim ---\n' +
        hookScript.replace(/^#!\/bin\/sh\r?\n/, '');
      fs.writeFileSync(hookPath, updated, { encoding: 'utf8', mode: 0o755 });
    } else {
      fs.writeFileSync(hookPath, hookScript, { encoding: 'utf8', mode: 0o755 });
    }
  } else {
    fs.writeFileSync(hookPath, hookScript, { encoding: 'utf8', mode: 0o755 });
  }

  try {
    fs.chmodSync(hookPath, 0o755);
  } catch {
    // Ignore chmod issues on Windows
  }

  if (!quiet) {
    log.success(
      `Installed Git Hook ${c.bold(c.brightCyan('.git/hooks/post-commit'))} ${c.gray('— Safely updates REPO_MAP.md after each commit')}`
    );
  }
}
