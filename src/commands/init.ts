function writeFileSafe(filePath: string, content: string, force: boolean): 'created' | 'updated' | 'skipped' {
  const exists = fs.existsSync(filePath);
  if (exists && !force) {
    // Still overwrite if it was previously generated by ctx-slim
    try {
      const existing = fs.readFileSync(filePath, 'utf8');
      if (!existing.includes('ctx-slim')) {
        return 'skipped';
      }
    } catch {
      return 'skipped';
    }
  }

  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(filePath, content, 'utf8');
  return exists ? 'updated' : 'created';
}

export function runInitCommand(options: InitOptions): void {
  if (options.global) {
    runGlobalInit(options);
    return;
  }

  const cwd = path.resolve(options.cwd);
  const projectName = path.basename(cwd);

  if (!options.quiet) {
    printBanner();
    log.step('Initializing ctx-slim in', cwd);
    console.log('');
  }

  // 1. Detect Tech Stack
  const stacks = detectStacks(cwd);
  if (!options.quiet) {
    if (stacks.length > 0) {
      const stackSummary = stacks
        .map((s) => `${c.bold(c.brightCyan(s.name))} ${c.gray(`(${s.matchedFiles.slice(0, 3).join(', ')})`)}`)
        .join(' + ');
      log.success(`Detected Tech Stack: ${stackSummary}`);
    } else {
      log.info(`No specific lockfile detected — applying universal polyglot optimization profile.`);
    }
  }

  // 2. Generate .claudeignore, .antigravityignore, .aiignore
  const ignoreContent = generateIgnoreContent(stacks);
  const ignoreTargets = ['.claudeignore', '.antigravityignore', '.aiignore'];

  for (const target of ignoreTargets) {
    const fullPath = path.join(cwd, target);
    const status = writeFileSafe(fullPath, ignoreContent, options.force);
    if (!options.quiet) {
      logFileStatus(target, status, 'Blocks lockfiles, build artifacts, caches & binaries');
    }
  }

  // 3. Generate CLAUDE.md and .antigravity/rules.md
  const claudeMdPath = path.join(cwd, 'CLAUDE.md');
  const claudeStatus = writeFileSafe(
    claudeMdPath,
    generateClaudeMd(projectName, stacks),
    options.force
  );
  if (!options.quiet) {
    logFileStatus('CLAUDE.md', claudeStatus, 'Diff-Only, Zero-Fluff, REPO_MAP-First & Slash commands');
  }

  const agRulesPath = path.join(cwd, '.antigravity', 'rules.md');
  const agStatus = writeFileSafe(
    agRulesPath,
    generateAntigravityRulesMd(projectName, stacks),
    options.force
  );
  if (!options.quiet) {
    logFileStatus(
      '.antigravity/rules.md',
      agStatus,
      'Antigravity agent rules & targeted line-range protocol'
    );
  }

  // 4. Generate .claude/commands/*.md for native slash command execution
  const slashCommands = generateClaudeSlashCommands();
  for (const [fileName, cmdContent] of Object.entries(slashCommands)) {
    const cmdPath = path.join(cwd, '.claude', 'commands', fileName);
    writeFileSafe(cmdPath, cmdContent, options.force);
  }
  if (!options.quiet) {
    log.success(
      `Configured Slash Commands: ${c.brightCyan('/diff')}, ${c.brightCyan('/plan-lite')}, ${c.brightCyan('/handoff')}, ${c.brightCyan('/slim')}`
    );
  }

  // 5. Generate initial REPO_MAP.md
  const mapResult = buildRepoMap({ cwd, output: 'REPO_MAP.md', quiet: true });
  fs.writeFileSync(path.join(cwd, 'REPO_MAP.md'), mapResult.markdown, 'utf8');
  if (!options.quiet) {
    log.success(
      `Generated ${c.bold(c.brightCyan('REPO_MAP.md'))} ${c.gray(`(${formatNumber(mapResult.totalFiles)} files, ${formatNumber(mapResult.totalSymbols)} symbols, ${mapResult.savingsPercent.toFixed(1)}% token reduction)`)}`
    );
  }

  // 6. Optional Git Hook (--with-hooks)
  if (options.withHooks) {
    installGitPostCommitHook(cwd, options.quiet);
  } else if (!options.quiet) {
    const gitDir = path.join(cwd, '.git');
    if (fs.existsSync(gitDir)) {
      log.info(
        `Tip: Run ${c.cyan('npx ctx-slim init --with-hooks')} to auto-update REPO_MAP.md on every ${c.cyan('git commit')}.`
      );
    }
  }

  if (!options.quiet) {
    console.log('');
    console.log(`  ${c.bgGreen(c.bold(' READY '))} ${c.bold('Your project is now token-optimized!')}`);
    console.log(
      `  ${c.gray('Next: Run')} ${c.brightCyan('npx ctx-slim stats')} ${c.gray('to inspect your token & USD savings.')}`
    );
    console.log('');
  }
}

function logFileStatus(
  relPath: string,
  status: 'created' | 'updated' | 'skipped',
  desc: string
): void {
  if (status === 'created') {
    log.success(`Created ${c.bold(c.brightCyan(relPath))} ${c.gray('— ' + desc)}`);
  } else if (status === 'updated') {
    log.success(`Updated ${c.bold(c.brightCyan(relPath))} ${c.gray('— ' + desc)}`);
  } else {
    log.warn(
      `Skipped ${c.bold(relPath)} ${c.gray('(already exists; pass --force to overwrite)')}`
    );
  }
}

function runGlobalInit(options: InitOptions): void {
  const homeDir = os.homedir();

  if (!options.quiet) {
    printBanner();
    log.step('Activating ctx-slim GLOBALLY for all projects in', homeDir);
    console.log('');
  }

  // 1. Global Claude Code Rules (~/.claude/CLAUDE.md)
  const globalClaudeMd = path.join(homeDir, '.claude', 'CLAUDE.md');
  const claudeStatus = writeFileSafe(
    globalClaudeMd,
    generateClaudeMd('All Projects (Global Profile)', []),
    options.force
  );
  if (!options.quiet) {
    logFileStatus(
      '~/.claude/CLAUDE.md',
      claudeStatus,
      'Global Claude Code rules (active across all projects)'
    );
  }

  // 2. Global Claude Code Slash Commands (~/.claude/commands/*.md)
  const slashCommands = generateClaudeSlashCommands();
  for (const [fileName, cmdContent] of Object.entries(slashCommands)) {
    const cmdPath = path.join(homeDir, '.claude', 'commands', fileName);
    writeFileSafe(cmdPath, cmdContent, options.force);
  }
  if (!options.quiet) {
    log.success(
      `Installed Global Slash Commands in ${c.bold(c.brightCyan('~/.claude/commands/'))}: ${c.brightCyan('/diff')}, ${c.brightCyan('/plan-lite')}, ${c.brightCyan('/handoff')}, ${c.brightCyan('/slim')}`
    );
  }

  // 3. Global Antigravity Rules (~/.antigravity/rules.md)
  const globalAgRules = path.join(homeDir, '.antigravity', 'rules.md');
  const agStatus = writeFileSafe(
    globalAgRules,
    generateAntigravityRulesMd('All Projects (Global Profile)', []),
    options.force
  );
  if (!options.quiet) {
    logFileStatus(
      '~/.antigravity/rules.md',
      agStatus,
      'Global Antigravity rules (active across all workspaces)'
    );
  }

  if (!options.quiet) {
    console.log('');
    console.log(
      `  ${c.bgGreen(c.bold(' GLOBAL READY '))} ${c.bold('ContextSlim is now active across ALL projects on your computer!')}`
    );
    console.log(
      `  ${c.gray('Tip: You can also run')} ${c.brightCyan('ctx-slim init --with-hooks')} ${c.gray('inside any specific repo to add Git post-commit hooks.')}`
    );
    console.log('');
  }
}

function installGitPostCommitHook(cwd: string, quiet?: boolean): void {
  const gitDir = path.join(cwd, '.git');
  if (!fs.existsSync(gitDir)) {
    if (!quiet) {
      log.warn(`Skipped Git hook installation: ${c.yellow('.git/')} directory not found.`);
    }
    return;
  }

  const hooksDir = path.join(gitDir, 'hooks');
  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }

  const hookPath = path.join(hooksDir, 'post-commit');
  const hookScript = generatePostCommitHook();

  if (fs.existsSync(hookPath)) {
    const existing = fs.readFileSync(hookPath, 'utf8');
    if (!existing.includes('ctx-slim')) {
      const appended =
        existing.trimEnd() +
        '\n\n# --- Added by ctx-slim ---\n' +
        hookScript.replace(/^#!\/bin\/sh\r?\n/, '');
      fs.writeFileSync(hookPath, appended, { encoding: 'utf8', mode: 0o755 });
    } else {
      fs.writeFileSync(hookPath, hookScript, { encoding: 'utf8', mode: 0o755 });
    }
  } else {
    fs.writeFileSync(hookPath, hookScript, { encoding: 'utf8', mode: 0o755 });
  }

  try {
    fs.chmodSync(hookPath, 0o755);
  } catch {
    // Ignore chmod issues on Windows
  }

  if (!quiet) {
    log.success(
      `Installed Git Hook ${c.bold(c.brightCyan('.git/hooks/post-commit'))} ${c.gray('— Auto-updates REPO_MAP.md after each commit')}`
    );
  }
}
