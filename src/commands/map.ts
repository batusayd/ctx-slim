import * as fs from 'fs';
import * as path from 'path';
import { CodeSymbol, FileMapEntry, MapOptions, RepoMapResult } from '../types';
import { IgnoreMatcher } from '../utils/ignore';
import {
  getLanguageForFile,
  isParsableSourceFile,
  isTextSourceFile,
  parseFileSymbols,
} from '../utils/parser';
import {
  c,
  estimateTokensFromText,
  formatBytes,
  formatNumber,
  log,
  printBanner,
} from '../utils/ui';

const MAX_FILE_SIZE_BYTES = 512 * 1024; // 512 KB cap for single source file parsing

export function buildRepoMap(options: MapOptions): RepoMapResult {
  const cwd = path.resolve(options.cwd);
  const maxDepth = options.maxDepth ?? 8;
  const matcher = new IgnoreMatcher(cwd);

  const entries: FileMapEntry[] = [];
  const treePaths: string[] = [];

  function walk(currentDir: string, depth: number): void {
    if (depth > maxDepth) return;

    let dirEntries: fs.Dirent[] = [];
    try {
      dirEntries = fs.readdirSync(currentDir, { withFileTypes: true });
    } catch {
      return;
    }

    // Sort directories first, then files alphabetically
    dirEntries.sort((a, b) => {
      if (a.isDirectory() && !b.isDirectory()) return -1;
      if (!a.isDirectory() && b.isDirectory()) return 1;
      return a.name.localeCompare(b.name);
    });

    for (const entry of dirEntries) {
      const fullPath = path.join(currentDir, entry.name);
      const relPath = path.relative(cwd, fullPath).replace(/\\/g, '/');

      if (matcher.isIgnored(relPath, entry.isDirectory())) {
        continue;
      }

      if (entry.isDirectory()) {
        treePaths.push(relPath + '/');
        walk(fullPath, depth + 1);
      } else if (entry.isFile()) {
        treePaths.push(relPath);
        processFile(fullPath, relPath);
      }
    }
  }

  function processFile(fullPath: string, relPath: string): void {
    if (!isTextSourceFile(relPath)) return;

    let stat: fs.Stats;
    try {
      stat = fs.statSync(fullPath);
    } catch {
      return;
    }

    if (stat.size > MAX_FILE_SIZE_BYTES) return;

    let content = '';
    try {
      content = fs.readFileSync(fullPath, 'utf8');
    } catch {
      return;
    }

    // Skip binary-like files containing null bytes
    if (content.includes('\0')) return;

    const lineCount = content.split(/\r?\n/).length;
    const estimatedFileTokens = estimateTokensFromText(content);
    const language = getLanguageForFile(relPath);
    const symbols = isParsableSourceFile(relPath) ? parseFileSymbols(relPath, content) : [];

    entries.push({
      relativePath: relPath,
      language,
      sizeBytes: stat.size,
      lineCount,
      estimatedTokens: estimatedFileTokens,
      symbols,
    });
  }

  walk(cwd, 0);

  const totalFiles = entries.length;
  const totalLines = entries.reduce((acc, e) => acc + e.lineCount, 0);
  const totalBytes = entries.reduce((acc, e) => acc + e.sizeBytes, 0);
  const totalSymbols = entries.reduce((acc, e) => acc + e.symbols.length, 0);
  const rawCodeTokens = entries.reduce((acc, e) => acc + e.estimatedTokens, 0);

  const generatedAt = new Date().toISOString();
  const projectName = path.basename(cwd);

  const treeAscii = renderDirectoryTree(projectName, treePaths);
  const symbolSection = renderSymbolIndex(entries);

  const headerLines = [
    `# REPO_MAP.md — ${projectName}`,
    '',
    '> **Auto-generated by `ctx-slim map`**',
    '> **AI Agent Instruction**: Check symbol `[Lstart-Lend]` line ranges below before reading large files in full.',
    '',
  ];

  const preliminaryBody = [
    '## 1. Directory Structure',
    '',
    '```text',
    treeAscii,
    '```',
    '',
    '## 2. Symbol & Line-Range Index',
    '',
    symbolSection,
    '',
  ].join('\n');

  const mapTokens = estimateTokensFromText(
    headerLines.join('\n') + '\n' + preliminaryBody + ' '.repeat(250)
  );
  const savingsPercent =
    rawCodeTokens > 0
      ? Math.max(0, Math.min(99.9, ((rawCodeTokens - mapTokens) / rawCodeTokens) * 100))
      : 0;

  const metricsTable = [
    '| Metric | Value |',
    '| :--- | :--- |',
    `| **Indexed Source Files** | ${formatNumber(totalFiles)} files (${formatNumber(totalLines)} lines / ${formatBytes(totalBytes)}) |`,
    `| **Extracted Symbols** | ${formatNumber(totalSymbols)} definitions with exact line ranges |`,
    `| **Full Repo Token Cost** | ~${formatNumber(rawCodeTokens)} tokens |`,
    `| **REPO_MAP Token Cost** | ~${formatNumber(mapTokens)} tokens (**${savingsPercent.toFixed(1)}% smaller**) |`,
    '',
  ].join('\n');

  const markdown = [...headerLines, metricsTable, preliminaryBody].join('\n');

  return {
    rootDir: cwd,
    generatedAt,
    totalFiles,
    totalLines,
    totalBytes,
    totalSymbols,
    rawCodeTokens,
    mapTokens,
    savingsPercent,
    entries,
    markdown,
  };
}

function renderDirectoryTree(rootName: string, relPaths: string[]): string {
  interface TreeNode {
    name: string;
    isDir: boolean;
    children: Map<string, TreeNode>;
  }

  const root: TreeNode = { name: rootName, isDir: true, children: new Map() };

  for (const p of relPaths) {
    const isDir = p.endsWith('/');
    const clean = isDir ? p.slice(0, -1) : p;
    const parts = clean.split('/');
    let curr = root;

    for (let i = 0; i < parts.length; i++) {
      const part = parts[i];
      const partIsDir = i < parts.length - 1 || isDir;
      let child = curr.children.get(part);
      if (!child) {
        child = { name: part, isDir: partIsDir, children: new Map() };
        curr.children.set(part, child);
      }
      curr = child;
    }
  }

  const lines: string[] = [`${rootName}/`];

  function traverse(node: TreeNode, prefix: string): void {
    const items = Array.from(node.children.values()).sort((a, b) => {
      if (a.isDir && !b.isDir) return -1;
      if (!a.isDir && b.isDir) return 1;
      return a.name.localeCompare(b.name);
    });

    items.forEach((item, idx) => {
      const isLast = idx === items.length - 1;
      const connector = isLast ? '└── ' : '├── ';
      const suffix = item.isDir ? '/' : '';
      lines.push(`${prefix}${connector}${item.name}${suffix}`);
      if (item.isDir && item.children.size > 0) {
        traverse(item, prefix + (isLast ? '    ' : '│   '));
      }
    });
  }

  traverse(root, '');
  return lines.join('\n');
}

function formatLineRange(sym: CodeSymbol): string {
  if (sym.lineEnd > sym.lineStart) {
    return `L${sym.lineStart}-L${sym.lineEnd}`;
  }
  return `L${sym.lineStart}`;
}

function renderSymbolIndex(entries: FileMapEntry[]): string {
  if (entries.length === 0) {
    return '_No source files detected._';
  }

  const blocks: string[] = [];

  for (const entry of entries) {
    const header = `### \`${entry.relativePath}\` _(${entry.language}, ${entry.lineCount}L, ~${entry.estimatedTokens} tok)_`;
    if (entry.symbols.length === 0) {
      blocks.push(`${header}\n- _No top-level symbols extracted (config/script/doc)_`);
      continue;
    }

    const symLines = entry.symbols.map((sym) => {
      const expBadge = sym.exported ? 'export ' : '';
      return `- \`[${formatLineRange(sym)}]\` **${sym.kind}** \`${expBadge}${sym.name}\``;
    });

    blocks.push(`${header}\n${symLines.join('\n')}`);
  }

  return blocks.join('\n\n');
}

export function runMapCommand(options: MapOptions): RepoMapResult {
  if (!options.quiet) {
    printBanner();
    log.step('Scanning repository & extracting AST/Regex symbol ranges...', options.cwd);
  }

  const result = buildRepoMap(options);
  const outPath = path.resolve(options.cwd, options.output || 'REPO_MAP.md');

  // Only write to disk if content actually changed (prevents unnecessary dirty working tree / mtime churn)
  let existingContent = '';
  if (fs.existsSync(outPath)) {
    try {
      existingContent = fs.readFileSync(outPath, 'utf8');
    } catch {
      existingContent = '';
    }
  }
  if (existingContent !== result.markdown) {
    fs.writeFileSync(outPath, result.markdown, 'utf8');
  }

  if (!options.quiet) {
    console.log('');
    log.success(
      `Generated ${c.bold(c.brightCyan(path.relative(options.cwd, outPath) || 'REPO_MAP.md'))}`
    );
    console.log(
      `    ${c.gray('├─')} Indexed Files   : ${c.bold(formatNumber(result.totalFiles))} (${formatNumber(result.totalLines)} lines)`
    );
    console.log(
      `    ${c.gray('├─')} Symbols Mapped  : ${c.bold(formatNumber(result.totalSymbols))} functions/classes/types with ${c.cyan('[Lstart-Lend]')}`
    );
    console.log(
      `    ${c.gray('├─')} Raw Code Tokens : ${c.yellow('~' + formatNumber(result.rawCodeTokens))} tokens`
    );
    console.log(
      `    ${c.gray('└─')} Map Token Size  : ${c.brightGreen('~' + formatNumber(result.mapTokens))} tokens (${c.bold(c.brightGreen(result.savingsPercent.toFixed(1) + '% smaller than full source'))})`
    );
    console.log('');
  }

  if (options.watch) {
    startMapWatcher(options, outPath);
  }

  return result;
}

function startMapWatcher(options: MapOptions, outPath: string): void {
  const cwd = path.resolve(options.cwd);
  const matcher = new IgnoreMatcher(cwd);
  const outRel = path.relative(cwd, outPath).replace(/\\/g, '/');

  log.info(
    `Watching ${c.brightCyan(cwd)} for file edits to keep ${c.bold(outRel)} live-updated... ${c.gray('(Press Ctrl+C to stop)')}`
  );

  let timer: NodeJS.Timeout | null = null;

  try {
    fs.watch(cwd, { recursive: true }, (_eventType, filename) => {
      if (!filename) return;
      const rel = filename.replace(/\\/g, '/');
      if (rel === outRel || rel === 'REPO_MAP.md' || rel === 'CONTEXT_STATE.md') return;
      if (matcher.isIgnored(rel, false) || !isTextSourceFile(rel)) return;

      if (timer) clearTimeout(timer);
      timer = setTimeout(() => {
        try {
          const updated = buildRepoMap(options);
          fs.writeFileSync(outPath, updated.markdown, 'utf8');
          if (!options.quiet) {
            const timeStr = new Date().toLocaleTimeString();
            log.success(
              `${c.gray(`[${timeStr}]`)} Refreshed ${c.brightCyan(outRel)} after change in ${c.white(rel)} (${updated.totalSymbols} symbols)`
            );
          }
        } catch {
          // Ignore transient write errors
        }
      }, 150);
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    log.warn(`Recursive watch not supported on this platform/directory: ${msg}`);
  }
}
